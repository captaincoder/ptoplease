  const H = 9; // cell height (7 + 2 descender rows)
  const glyphs = {};
  const order = Object.keys(G);
  let atlasW = 0;
  for (const ch of order) {
    const rows = G[ch].split('|');
    const w = rows[0].length;
    glyphs[ch] = { rows, w, x: atlasW };
    atlasW += w + 1;
  }
  const atlases = {};
  function atlas(color) {
    if (atlases[color]) return atlases[color];
    const c = document.createElement('canvas');
    c.width = atlasW; c.height = H;
    const g = c.getContext('2d');
    g.fillStyle = color;
    for (const ch of order) {
      const gl = glyphs[ch];
      gl.rows.forEach((r, y) => {
        for (let x = 0; x < r.length; x++) if (r[x] === '#') g.fillRect(gl.x + x, y, 1, 1);
      });
    }
    atlases[color] = c;
    return c;
  }
  function norm(s) {
    return String(s).replace(/™/g, 'TM').replace(/…/g, '...').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[—–]/g, '-').replace(/[ñ]/g, 'n').replace(/[é]/g, 'e');
  }
  function glyph(ch) { return glyphs[ch] || glyphs['?']; }
  function width(s, scale = 1) {
    s = norm(s);
    let w = 0;
    for (const ch of s) w += glyph(ch).w + 1;
    return Math.max(0, w - 1) * scale;
  }
  // draw text; returns width
  function text(ctx, s, x, y, color = '#222', scale = 1) {
    s = norm(s);
    const a = atlas(color);
    let cx = Math.round(x);
    y = Math.round(y);
    for (const ch of s) {
      const gl = glyph(ch);
      ctx.drawImage(a, gl.x, 0, gl.w, H, cx, y, gl.w * scale, H * scale);
      cx += (gl.w + 1) * scale;
    }
    return cx - x;
  }
  function wrap(s, maxW, scale = 1) {
    const out = [];
    for (const para of norm(s).split('\n')) {
      let line = '';
      for (const word of para.split(' ')) {
        const t = line ? line + ' ' + word : word;
        if (width(t, scale) <= maxW || !line) line = t;
        else { out.push(line); line = word; }
      }
      out.push(line);
    }
    return out;
  }
  window.Font = { text, width, wrap, H, LINE: 10 };
